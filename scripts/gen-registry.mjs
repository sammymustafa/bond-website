#!/usr/bin/env node
/**
 * Generates src/content/registry.ts from every .ts file under src/content/pages.
 * Run after adding or removing a content page:  node scripts/gen-registry.mjs
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pagesDir = join(root, "src", "content", "pages");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".") || name.startsWith("_")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (name.endsWith(".ts")) out.push(full);
  }
  return out;
}

const files = walk(pagesDir)
  .map((f) => relative(pagesDir, f).replace(/\\/g, "/").replace(/\.ts$/, ""))
  .sort();

const imports = files.map((f, i) => `import p${i} from "./pages/${f}";`).join("\n");
const list = files.map((_, i) => `p${i}`).join(", ");

const out = `// Generated by scripts/gen-registry.mjs. Do not edit by hand.
import type { SeoPage } from "./types";
${imports}

export const pages: SeoPage[] = [${list}];
`;

writeFileSync(join(root, "src", "content", "registry.ts"), out);
console.log(`registry: ${files.length} pages`);
